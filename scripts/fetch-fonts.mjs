// Downloads latin woff2 subsets for the three brand fonts and generates
// src/styles/fonts.css with local @font-face rules (font-display: swap).
import { mkdir, writeFile } from 'node:fs/promises';

const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';
const FAMILIES = [
  { name: 'Space Grotesk', query: 'family=Space+Grotesk:wght@500;700', prefix: 'space-grotesk' },
  { name: 'Inter', query: 'family=Inter:wght@400;500;600;700', prefix: 'inter' },
  { name: 'JetBrains Mono', query: 'family=JetBrains+Mono:wght@400;600', prefix: 'jetbrains-mono' },
];

await mkdir('src/assets/fonts', { recursive: true });
let css = '/* Self-hosted fonts — generated by scripts/fetch-fonts.mjs. No Google Fonts requests. */\n';

for (const fam of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?${fam.query}&display=swap`;
  const text = await (await fetch(url, { headers: { 'User-Agent': UA } })).text();
  // Keep only /* latin */ blocks; dedupe identical variable font files per family.
  const seen = new Map();
  for (const block of text.split('/*').filter((b) => b.startsWith(' latin */'))) {
    const weight = block.match(/font-weight:\s*(\d+)/)?.[1];
    const srcUrl = block.match(/url\((https:[^)]+)\)/)?.[1];
    if (!weight || !srcUrl) continue;
    if (!seen.has(srcUrl)) {
      const buf = Buffer.from(await (await fetch(srcUrl, { headers: { 'User-Agent': UA } })).arrayBuffer());
      const fname = `${fam.prefix}-${seen.size}.woff2`;
      await writeFile(`src/assets/fonts/${fname}`, buf);
      seen.set(srcUrl, fname);
      console.log(`${fname}: ${(buf.length / 1024).toFixed(1)} KB`);
    }
    css += `@font-face {\n  font-family: '${fam.name}';\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: swap;\n  src: url('../assets/fonts/${seen.get(srcUrl)}') format('woff2');\n}\n`;
  }
}
await writeFile('src/styles/fonts.css', css);
console.log('Wrote src/styles/fonts.css');
